"""Final prediction/evaluation have no path back into model selection."""

from pathlib import Path

import joblib
import pandas as pd
from sklearn.metrics import classification_report

from .data import file_hash, labels, read_csv
from .features import ImageFeatures
from .io import write_json
from .metrics import score_model
from .submission import check_solution_stage


def protect_outputs(output_path, model_path, input_path, include_sidecar=False):
    destination = Path(output_path).resolve()
    protected = {Path(model_path).resolve(), Path(input_path).resolve()}
    outputs = [destination]
    if include_sidecar:
        outputs.append(destination.with_suffix(destination.suffix + ".metadata.json"))
    for path in outputs:
        if path in protected or path.exists():
            raise ValueError(f"Output must be a new file and cannot overwrite input/model: {path}")
    return destination


def load_solution(path, image_root=None):
    # joblib uses pickle: only load artifacts generated by a trusted source.
    artifact = joblib.load(path)
    if artifact.get("metadata", {}).get("schema_version") != 1:
        raise ValueError("Unsupported model artifact schema")
    model, metadata = artifact["model"], artifact["metadata"]
    check_solution_stage(metadata)
    if image_root:
        if metadata["profile"]["data_type"] != "image":
            raise ValueError("--image-root is only valid for image models")
        prep = model.named_steps["preprocess"]
        # A dummy baseline uses constant features and does not read images.
        if hasattr(prep, "named_steps") and isinstance(prep.named_steps.get("images"), ImageFeatures):
            prep.named_steps["images"].root = str(Path(image_root).resolve())
    return model, metadata


def checked_input(path, metadata):
    config = metadata["config"]
    frame = read_csv(path, config["id_column"], config["target_column"])
    missing = set(metadata["profile"]["features"]) - set(frame.columns)
    if missing:
        raise ValueError(f"Input missing required features: {sorted(missing)}")
    return frame


def predict(model_path, input_path, output_path, image_root=None):
    destination = protect_outputs(output_path, model_path, input_path, include_sidecar=True)
    model, metadata = load_solution(model_path, image_root)
    frame = checked_input(input_path, metadata)
    result = pd.DataFrame({"prediction": model.predict(frame)})
    id_column = metadata["config"]["id_column"]
    if id_column:
        if id_column in {"prediction"} or id_column.startswith("probability_"):
            raise ValueError("ID column name conflicts with prediction output columns")
        result.insert(0, id_column, frame[id_column].reset_index(drop=True))
    classes = [str(c) for c in model.classes_]
    if hasattr(model, "predict_proba"):
        proba = model.predict_proba(frame)
        for index in range(len(classes)):
            result[f"probability_{index}"] = proba[:, index]
    destination.parent.mkdir(parents=True, exist_ok=True)
    check_solution_stage(metadata)
    result.to_csv(destination, index=False)
    write_json(destination.with_suffix(destination.suffix + ".metadata.json"), {
        "classes_in_probability_column_order": classes,
        "model_sha256": file_hash(model_path), "input_sha256": file_hash(input_path),
        "submission": metadata.get("submission"), "model_usage": metadata.get("model_usage"),
    })
    return {"rows": len(result), "output": str(destination)}


def evaluate(model_path, input_path, output_path, image_root=None):
    destination = protect_outputs(output_path, model_path, input_path)
    model, metadata = load_solution(model_path, image_root)
    input_hash = file_hash(input_path)
    fitting_hashes = metadata.get("data_sha256", {})
    if input_hash in {fitting_hashes.get("train_csv"), fitting_hashes.get("validation_csv")}:
        raise ValueError("Final evaluation cannot reuse the training or validation CSV")
    frame = checked_input(input_path, metadata)
    config = metadata["config"]
    y = labels(frame, config["target_column"])
    if set(y) - set(str(c) for c in model.classes_):
        raise ValueError("Evaluation labels contain classes absent from the final model")
    score = score_model(model, frame, y, config["metric"], config["positive_label"])
    result = {
        "metric": config["metric"], "score": score, "rows": len(frame),
        "model_sha256": file_hash(model_path), "input_sha256": input_hash,
        "classification_report": classification_report(y, model.predict(frame), output_dict=True, zero_division=0),
        "source_sha256": metadata["source_sha256"],
        "submission": metadata.get("submission"), "model_usage": metadata.get("model_usage"),
        "usage": "Final evaluation only; this score is not passed to search or selection",
    }
    destination.parent.mkdir(parents=True, exist_ok=True)
    check_solution_stage(metadata)
    write_json(destination, result)
    return result
